// Builds the icon font the app loads: only the Remix icons named in the code (about a fifth of
// the set), so pages don't wait for all 3,000. Writes:
//   src/app/icons.css + src/app/icons.woff   the subset, imported by the root layouts
//   src/components/ui/icon-names.js          the names in it, so <Icon> knows what's there
//   public/icons/remixicon.css + .woff2       the full set, which <Icon> loads only for a name
//                                            outside the subset (e.g. one chosen in a list)
// Run after adding icons:  yarn icons   (needs Python fontTools: pip3 install fonttools)
import { execFileSync } from "node:child_process"
import { copyFileSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs"
import path from "node:path"

const FONTS = "node_modules/remixicon/fonts"
const css = readFileSync(path.join(FONTS, "remixicon.css"), "utf8")
// name → "\eXXX"
const glyphs = new Map([...css.matchAll(/\.ri-([a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)";/g)].map((m) => [m[1], m[2]]))

// Every quoted word in the source that is an icon name
const used = new Set()
const walk = (dir) => {
  for (const f of readdirSync(dir)) {
    const p = path.join(dir, f)
    if (statSync(p).isDirectory()) walk(p)
    else if (/\.(jsx?|mjs|json)$/.test(f) && !p.endsWith("remix-icons.json") && !p.endsWith("icon-names.js"))
      for (const m of readFileSync(p, "utf8").matchAll(/["'`]([a-z0-9]+(?:-[a-z0-9]+)*)["'`]/g)) if (glyphs.has(m[1])) used.add(m[1])
  }
}
walk("src")
const names = [...used].sort()

execFileSync("pyftsubset", [
  path.join(FONTS, "remixicon.ttf"),
  `--unicodes=${names.map((n) => `U+${glyphs.get(n)}`).join(",")}`,
  "--flavor=woff",
  "--output-file=src/app/icons.woff",
  "--no-hinting",
  "--desubroutinize",
], { stdio: ["ignore", "inherit", "inherit"] })

const base = `/* Generated by scripts/build-icons.mjs: the Remix icons the app uses. Don't edit. */
@font-face {
  font-family: "remixicon";
  src: url("./icons.woff") format("woff");
  font-display: block;
}
[class^="ri-"], [class*=" ri-"] {
  font-family: "remixicon" !important;
  font-style: normal;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}
`
writeFileSync("src/app/icons.css", base + names.map((n) => `.ri-${n}:before { content: "\\${glyphs.get(n)}"; }`).join("\n") + "\n")
writeFileSync("src/components/ui/icon-names.js", `// Generated by scripts/build-icons.mjs: the icons in the app's own font. Don't edit.\nexport const ICON_NAMES = new Set(${JSON.stringify(names)})\n`)

// The full set, for names outside the subset. A different family name, so it never replaces the subset
copyFileSync(path.join(FONTS, "remixicon.woff2"), "public/icons/remixicon.woff2")
const full = css
  .replace(/@font-face\s*\{[\s\S]*?\}/, `@font-face {\n  font-family: "remixicon-all";\n  src: url("remixicon.woff2") format("woff2");\n  font-display: block;\n}`)
  .replace(/\[class\^="ri-"\], \[class\*=" ri-"\] \{[\s\S]*?\}/, `.ri-all[class^="ri-"], .ri-all[class*=" ri-"] {\n  font-family: "remixicon-all" !important;\n  font-style: normal;\n  -webkit-font-smoothing: antialiased;\n}`)
writeFileSync("public/icons/remixicon.css", full)

const size = (f) => `${Math.round(statSync(f).size / 1024)} KB`
console.log(`${names.length} of ${glyphs.size} icons · icons.woff ${size("src/app/icons.woff")} · icons.css ${size("src/app/icons.css")}`)
